//! Reference entries for the JavaScript pattern surface.
//!
//! These are the pattern methods and globals the score realm installs that
//! the engine does not implement as native combinators. The engine plays
//! them through the embedded score semantics, so their documentation lives
//! here, beside the bindings, instead of in a mirror that could drift.
//!
//! Entries whose name another entry already claims (`slowcat` beside `cat`,
//! `timecat` beside `stepcat`) keep the mirror's first-come precedence: the
//! reference resolves the name to whichever entry ingests first, exactly as
//! the mirror's document order does today.
//!
//! Documentation text from the Strudel project (AGPL-3.0-or-later),
//! https://strudel.cc.

